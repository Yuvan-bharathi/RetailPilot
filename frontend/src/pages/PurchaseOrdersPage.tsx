import { useState } from "react";
import { Link } from "react-router";
import { CheckCircle2, ChevronRight, ClipboardList, PackageCheck } from "lucide-react";

import { usePurchaseOrders } from "../api/hooks";
import type { POStatus, PurchaseOrderDTO } from "../api/types";
import { useAuth } from "../app/AuthContext";
import { formatINR, formatDateTimeIST } from "../lib/format";

export function PurchaseOrdersPage() {
  const { user } = useAuth();
  const [statusFilter, setStatusFilter] = useState<POStatus | "ALL">("ALL");
  const [selectedPo, setSelectedPo] = useState<PurchaseOrderDTO | null>(null);

  const { data: page, isLoading } = usePurchaseOrders({
    store_id: user?.role === "STORE_SUPERVISOR" ? user.store?.store_id : undefined,
    status: statusFilter === "ALL" ? undefined : statusFilter,
  });

  const orders = page?.items ?? [];

  const getStatusBadge = (status: POStatus) => {
    switch (status) {
      case "DRAFT":
        return (
          <span className="rounded-full bg-neutral-bg px-2.5 py-0.5 text-xs font-semibold text-neutral">Draft</span>
        );
      case "PENDING_L1":
        return (
          <span className="rounded-full bg-warning-bg px-2.5 py-0.5 text-xs font-semibold text-warning">
            L1 Pending
          </span>
        );
      case "PENDING_L2":
        return (
          <span className="rounded-full bg-purple-100 px-2.5 py-0.5 text-xs font-semibold text-purple-800">
            L2 Super Admin
          </span>
        );
      case "APPROVED":
        return (
          <span className="rounded-full bg-blue-100 px-2.5 py-0.5 text-xs font-semibold text-blue-800">Approved</span>
        );
      case "SUBMITTED":
        return (
          <span className="rounded-full bg-indigo-100 px-2.5 py-0.5 text-xs font-semibold text-indigo-800">
            Submitted
          </span>
        );
      case "RECEIVED":
        return (
          <span className="rounded-full bg-success-bg px-2.5 py-0.5 text-xs font-semibold text-success">Received</span>
        );
      case "SPLIT":
        return (
          <span className="rounded-full bg-neutral-bg px-2.5 py-0.5 text-xs font-semibold text-neutral">
            Split Order
          </span>
        );
      case "REJECTED":
        return (
          <span className="rounded-full bg-danger-bg px-2.5 py-0.5 text-xs font-semibold text-danger">Rejected</span>
        );
      default:
        return (
          <span className="rounded-full bg-neutral-bg px-2.5 py-0.5 text-xs font-semibold text-neutral">{status}</span>
        );
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-ink">Purchase Orders</h1>
          <p className="text-sm text-ink-secondary">
            Consolidated supplier orders generated by the autonomous PO builder.
          </p>
        </div>

        {/* Status filters */}
        <div className="flex flex-wrap gap-1.5">
          {(["ALL", "SUBMITTED", "APPROVED", "PENDING_L1", "PENDING_L2", "RECEIVED"] as const).map((s) => (
            <button
              key={s}
              type="button"
              onClick={() => setStatusFilter(s)}
              className={`rounded-button px-3 py-1.5 text-xs font-medium transition ${
                statusFilter === s
                  ? "bg-brand text-white shadow-xs"
                  : "border border-border bg-surface text-ink-secondary hover:text-ink"
              }`}
            >
              {s.replace("_", " ")}
            </button>
          ))}
        </div>
      </div>

      {isLoading ? (
        <div className="h-64 animate-pulse rounded-card border border-border bg-surface" />
      ) : orders.length === 0 ? (
        <div className="rounded-card border border-border bg-surface p-12 text-center shadow-card">
          <ClipboardList className="mx-auto h-12 w-12 text-ink-secondary/60" />
          <h3 className="mt-3 text-base font-semibold text-ink">No purchase orders found</h3>
          <p className="mt-1 text-sm text-ink-secondary">No purchase orders match your status filter.</p>
        </div>
      ) : (
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
          <div className="space-y-3 lg:col-span-2">
            <div className="overflow-hidden rounded-card border border-border bg-surface shadow-card">
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs">
                  <thead className="border-b border-divider bg-app/50 text-ink-secondary">
                    <tr>
                      <th className="py-3 px-4 font-medium">Supplier</th>
                      <th className="py-3 px-4 font-medium text-right">Order Value</th>
                      <th className="py-3 px-4 font-medium text-center">Lines</th>
                      <th className="py-3 px-4 font-medium text-center">Status</th>
                      <th className="py-3 px-4 font-medium text-right">Created</th>
                      <th className="py-3 px-4"></th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-divider">
                    {orders.map((po) => {
                      const isSelected = selectedPo?.po_id === po.po_id;
                      return (
                        <tr
                          key={po.po_id}
                          onClick={() => setSelectedPo(po)}
                          className={`cursor-pointer transition ${isSelected ? "bg-brand-soft/20" : "hover:bg-app/40"}`}
                        >
                          <td className="py-3.5 px-4">
                            <div className="font-semibold text-ink">{po.supplier.name}</div>
                            <div className="text-[11px] text-ink-secondary">{po.required_level} Approval</div>
                          </td>
                          <td className="py-3.5 px-4 text-right font-bold text-ink tabular">
                            {formatINR(po.total_value)}
                          </td>
                          <td className="py-3.5 px-4 text-center tabular font-medium text-ink">{po.lines.length}</td>
                          <td className="py-3.5 px-4 text-center">{getStatusBadge(po.status)}</td>
                          <td className="py-3.5 px-4 text-right text-ink-secondary tabular">
                            {formatDateTimeIST(po.created_at).split(",")[0]}
                          </td>
                          <td className="py-3.5 px-4 text-right">
                            <ChevronRight className="h-4 w-4 text-ink-secondary" />
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            </div>
          </div>

          {/* Right: Selected PO Preview Drawer */}
          <div>
            {selectedPo ? (
              <div className="rounded-card border border-border bg-surface p-5 shadow-card space-y-4">
                <div className="flex items-center justify-between border-b border-divider pb-3">
                  <div>
                    <h2 className="text-base font-bold text-ink">{selectedPo.supplier.name}</h2>
                    <p className="text-xs text-ink-secondary">Order ID: {selectedPo.po_id.slice(0, 8)}…</p>
                  </div>
                  {getStatusBadge(selectedPo.status)}
                </div>

                <div className="grid grid-cols-2 gap-3 text-xs">
                  <div className="rounded-card bg-app/50 p-2.5 border border-border">
                    <span className="text-ink-secondary">Total Value</span>
                    <div className="mt-1 font-bold text-ink tabular text-sm">{formatINR(selectedPo.total_value)}</div>
                  </div>
                  <div className="rounded-card bg-app/50 p-2.5 border border-border">
                    <span className="text-ink-secondary">Line Items</span>
                    <div className="mt-1 font-bold text-ink tabular text-sm">{selectedPo.lines.length} lines</div>
                  </div>
                </div>

                {/* Lines breakdown */}
                <div>
                  <h3 className="text-xs font-semibold uppercase tracking-wider text-ink-secondary mb-2">
                    Line Details
                  </h3>
                  <div className="max-h-60 overflow-y-auto divide-y divide-divider border rounded-card border-border text-xs">
                    {selectedPo.lines.map((ln) => (
                      <div key={ln.po_line_id} className="p-2.5">
                        <div className="flex items-center justify-between font-semibold text-ink">
                          <span>{ln.product.name}</span>
                          <span className="tabular">{ln.qty} units</span>
                        </div>
                        <div className="flex items-center justify-between text-[11px] text-ink-secondary mt-0.5">
                          <span>{ln.store.name}</span>
                          <span className="tabular">{formatINR(ln.line_value)}</span>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>

                {/* Direct action links */}
                {selectedPo.status === "SUBMITTED" && user?.role === "STORE_SUPERVISOR" && (
                  <Link
                    to="/goods-receipt"
                    className="flex w-full items-center justify-center gap-1.5 rounded-button bg-brand py-2 text-xs font-semibold text-white shadow-xs hover:bg-brand-hover"
                  >
                    <PackageCheck className="h-4 w-4" />
                    Record Goods Delivery
                  </Link>
                )}

                {(selectedPo.status === "PENDING_L1" || selectedPo.status === "PENDING_L2") && (
                  <Link
                    to="/approvals"
                    className="flex w-full items-center justify-center gap-1.5 rounded-button bg-brand py-2 text-xs font-semibold text-white shadow-xs hover:bg-brand-hover"
                  >
                    <CheckCircle2 className="h-4 w-4" />
                    Go to Approval Decision
                  </Link>
                )}
              </div>
            ) : (
              <div className="rounded-card border border-border bg-surface p-6 text-center text-xs text-ink-secondary shadow-card">
                Select a purchase order to view its line-level breakdown.
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
