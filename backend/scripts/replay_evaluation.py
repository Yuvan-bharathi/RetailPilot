"""Historical replay of the last 28 days: forecast error (WMAPE) and reorder-decision accuracy (Phase 9, D-45).

Every figure in the report is computed here from the synthetic dataset — nothing is typed in.

    cd backend && uv run python -m scripts.replay_evaluation                # full profile, writes docs/EVALUATION_REPORT.md
    cd backend && uv run python -m scripts.replay_evaluation --profile small --out <file>

Method (rolling origin, no look-ahead):
- Holdout = the last `holdout_days` (28) of history; origins every `step_days` (7) → 4 origins.
- At each origin every store-SKU is forecast from the history BEFORE the origin only, twice: the baseline
  (D-30) and model selection (D-45: ETS / Croston-SBA / TSB chosen by backtest, else baseline).
- Actual = units sold over that store-SKU's demand window (lead time of its supplier for that store + review
  period) starting at the origin. Windows containing a stockout day are excluded: their sales are censored.
- Forecast WMAPE = Σ|forecast × window − actual| / Σ actual; bias = Σ(forecast × window − actual) / Σ actual.
- Reorder decision: requirement = own_requirement(daily demand, lead, review, safety, min display) with the
  forecast vs with the actual demand of the window; available = closing stock the day before the origin + the
  receipts that arrive within the window (already ordered). Need = requirement > available. Reported: accuracy,
  precision, recall of the need flag and WMAPE of the need quantity.
Caveat: the data is synthetic, generated by our own demand model; the numbers show how well the planning logic
fits those patterns, not real-world accuracy.
"""

from __future__ import annotations

import argparse
import tempfile
from dataclasses import dataclass, field
from datetime import UTC, date, datetime, timedelta
from pathlib import Path
from typing import Any

import pandas as pd

from app.tools.forecast import ForecastTools as FT
from app.tools.requirement import RequirementCalculator as RC
from data.synthetic.config import GeneratorConfig
from data.synthetic.generate import generate
from data.synthetic.reader import Dataset, load_dataset

REPORT = Path(__file__).resolve().parents[2] / "docs" / "EVALUATION_REPORT.md"
VARIANTS = ("BASELINE", "MODEL_SELECTION")


@dataclass
class Evaluation:
    profile: str
    seed: int
    origins: list[date]
    rows: pd.DataFrame  # one row per store-SKU-origin-variant
    excluded_censored: int
    methods: dict[str, int] = field(default_factory=dict)


# --- data preparation --------------------------------------------------------------------------------------------


def daily_frame(ds: Dataset) -> pd.DataFrame:
    """[store_id, product_id, unique_id, ds, y, is_stockout, closing_on_hand] for every listed store-SKU and day."""
    lines = ds.sales_lines[~ds.sales_lines["is_return"] & ~ds.sales_lines["is_voided"]]
    sold = lines.groupby(["store_id", "product_id", "txn_date"], as_index=False)["qty"].sum()
    sold = sold.rename(columns={"txn_date": "ds", "qty": "y"})
    snaps = ds.stock_snapshots.rename(columns={"snapshot_date": "ds"})[
        ["store_id", "product_id", "ds", "closing_on_hand"]
    ]
    listed = ds.store_products[ds.store_products["is_listed"]][["store_id", "product_id"]]
    days = pd.DataFrame({"ds": sorted(snaps["ds"].unique())})
    frame = listed.merge(days, how="cross")
    frame = frame.merge(sold, on=["store_id", "product_id", "ds"], how="left")
    frame = frame.merge(snaps, on=["store_id", "product_id", "ds"], how="left")
    frame["y"] = frame["y"].fillna(0).astype(float)
    frame["is_stockout"] = frame["closing_on_hand"].fillna(0) <= 0
    frame["unique_id"] = frame["store_id"].astype(str) + ":" + frame["product_id"].astype(str)
    return frame.sort_values(["unique_id", "ds"], kind="stable").reset_index(drop=True)


def planning_terms(ds: Dataset) -> pd.DataFrame:
    """Per store-SKU: lead time of the preferred supplier for that store, review, safety, min display, category."""
    sp = ds.store_products[ds.store_products["is_listed"]].copy()
    terms = ds.supplier_store_terms.rename(columns={"supplier_id": "preferred_supplier_id"})
    sp = sp.merge(terms[["preferred_supplier_id", "store_id", "lead_time_days"]], how="left")
    defaults = ds.suppliers.set_index("supplier_id")["default_lead_time_days"]
    missing = sp["lead_time_days"].isna()
    sp.loc[missing, "lead_time_days"] = sp.loc[missing, "preferred_supplier_id"].map(defaults)
    sp["lead_time_days"] = sp["lead_time_days"].astype(int)
    sp = sp.merge(ds.products[["product_id", "category"]], on="product_id")
    sp["unique_id"] = sp["store_id"].astype(str) + ":" + sp["product_id"].astype(str)
    return sp.set_index("unique_id")


# --- evaluation ----------------------------------------------------------------------------------------------------


def evaluate(
    ds: Dataset, profile: str, seed: int, holdout_days: int = 28, step_days: int = 7, horizon: int = 14
) -> Evaluation:
    frame = daily_frame(ds)
    terms = planning_terms(ds)
    end = max(frame["ds"])
    holdout_start = end - timedelta(days=holdout_days - 1)
    origins = [holdout_start + timedelta(days=k * step_days) for k in range(holdout_days // step_days)]
    receipts = ds.receipts.groupby(["store_id", "product_id", "receipt_date"], as_index=False)["qty"].sum()
    receipts["unique_id"] = receipts["store_id"].astype(str) + ":" + receipts["product_id"].astype(str)
    by_uid = {uid: g.set_index("ds") for uid, g in frame.groupby("unique_id", sort=False)}
    rec_by_uid = {
        uid: g.set_index("receipt_date")["qty"] for uid, g in receipts.groupby("unique_id", sort=False)
    }

    rows: list[dict[str, Any]] = []
    methods: dict[str, int] = {}
    excluded = 0
    for origin in origins:
        train = frame[frame["ds"] < origin][["unique_id", "ds", "y", "is_stockout"]]
        baseline = FT.baseline_avg_daily(train, window_days=28)
        selected = FT.select_best(FT.backtest_models(train, horizon=horizon), baseline)
        forecasts = {
            "BASELINE": baseline.set_index("unique_id")["daily_demand"],
            "MODEL_SELECTION": selected.set_index("unique_id")["daily_demand"],
        }
        chosen_method = selected.set_index("unique_id")["method"]
        for method, count in chosen_method.value_counts().items():
            methods[str(method)] = methods.get(str(method), 0) + int(count)
        for uid, t in terms.iterrows():
            series = by_uid.get(str(uid))
            if series is None:
                continue
            window = int(t["lead_time_days"]) + int(t["review_period_days"])
            span = [origin + timedelta(days=i) for i in range(window)]
            if span[-1] > end:
                continue
            in_window = series.loc[span]
            if bool(in_window["is_stockout"].any()):
                excluded += 1
                continue
            actual = float(in_window["y"].sum())
            before = origin - timedelta(days=1)
            on_hand = float(series.loc[before, "closing_on_hand"]) if before in series.index else 0.0
            arriving = rec_by_uid.get(str(uid))
            incoming = (
                float(arriving[(arriving.index >= origin) & (arriving.index <= span[-1])].sum())
                if arriving is not None
                else 0.0
            )
            available = int(on_hand + incoming)
            args = (
                int(t["lead_time_days"]),
                int(t["review_period_days"]),
                int(t["safety_stock_days"]),
                int(t["min_display_qty"]),
            )
            actual_req = RC.own_requirement(actual / window, *args)
            for variant in VARIANTS:
                daily = float(forecasts[variant].get(uid, 0.0))
                pred_req = RC.own_requirement(daily, *args)
                rows.append(
                    {
                        "origin": origin,
                        "unique_id": uid,
                        "category": t["category"],
                        "variant": variant,
                        "window": window,
                        "forecast": daily * window,
                        "actual": actual,
                        "pred_need": max(0, pred_req - available),
                        "actual_need": max(0, actual_req - available),
                    }
                )
    return Evaluation(profile, seed, origins, pd.DataFrame(rows), excluded, methods)


# --- metrics and report ----------------------------------------------------------------------------------------------


def metrics(rows: pd.DataFrame) -> dict[str, float]:
    actual = rows["actual"].sum()
    error = (rows["forecast"] - rows["actual"]).abs().sum()
    pred, real = rows["pred_need"] > 0, rows["actual_need"] > 0
    tp, fp, fn = int((pred & real).sum()), int((pred & ~real).sum()), int((~pred & real).sum())
    need_total = rows["actual_need"].sum()
    return {
        "n": float(len(rows)),
        "wmape": float(error / actual) if actual else float("nan"),
        "bias": float((rows["forecast"] - rows["actual"]).sum() / actual) if actual else float("nan"),
        "accuracy": float((pred == real).mean()) if len(rows) else float("nan"),
        "precision": tp / (tp + fp) if tp + fp else float("nan"),
        "recall": tp / (tp + fn) if tp + fn else float("nan"),
        "need_wmape": float((rows["pred_need"] - rows["actual_need"]).abs().sum() / need_total)
        if need_total
        else float("nan"),
    }


def _pct(x: float) -> str:
    return "—" if x != x else f"{x * 100:.1f}%"


def render(ev: Evaluation) -> str:
    overall = {v: metrics(ev.rows[ev.rows["variant"] == v]) for v in VARIANTS}
    lines = [
        "# Evaluation replay — last 28 days",
        "",
        f"Generated {datetime.now(UTC):%Y-%m-%d %H:%M} UTC by `scripts/replay_evaluation.py` from the synthetic dataset "
        f"(profile `{ev.profile}`, seed {ev.seed}). Origins: {', '.join(str(o) for o in ev.origins)}. "
        f"Every number below is computed by the script.",
        "",
        "> The data is synthetic (our own demand generator). These figures show how well the planning logic fits",
        "> those demand patterns; they are not a measure of real-world accuracy.",
        "",
        "## Forecast error and reorder decisions",
        "",
        "| Variant | Store-SKU windows | Forecast WMAPE | Bias | Need accuracy | Precision | Recall | Need-qty WMAPE |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for v in VARIANTS:
        m = overall[v]
        lines.append(
            f"| {v.replace('_', ' ').title()} | {int(m['n']):,} | {_pct(m['wmape'])} | {_pct(m['bias'])} | "
            f"{_pct(m['accuracy'])} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_pct(m['need_wmape'])} |"
        )
    lines += [
        "",
        f"Windows excluded because they contain a stockout day (censored sales): {ev.excluded_censored:,}.",
        "",
        "## Forecast WMAPE by category",
        "",
        "| Category | Windows | Baseline | Model selection |",
        "|---|---:|---:|---:|",
    ]
    for category, group in ev.rows.groupby("category", sort=True):
        b = metrics(group[group["variant"] == "BASELINE"])
        s = metrics(group[group["variant"] == "MODEL_SELECTION"])
        lines.append(f"| {category} | {int(b['n']):,} | {_pct(b['wmape'])} | {_pct(s['wmape'])} |")
    total = sum(ev.methods.values()) or 1
    lines += [
        "",
        "## Methods chosen by model selection (all origins)",
        "",
        "| Method | Store-SKU forecasts | Share |",
        "|---|---:|---:|",
        *(
            f"| {m} | {n:,} | {n / total * 100:.1f}% |"
            for m, n in sorted(ev.methods.items(), key=lambda kv: -kv[1])
        ),
        "",
        "## Definitions",
        "",
        "- **Forecast WMAPE** = Σ|forecast × window − actual| / Σ actual over store-SKU demand windows "
        "(window = supplier lead time for that store + review period). **Bias** = Σ(forecast − actual) / Σ actual.",
        "- **Need** = own requirement > available (closing stock before the origin + receipts arriving in the window). "
        "Accuracy / precision / recall compare the need flag from the forecast with the flag from actual demand; "
        "**need-qty WMAPE** compares the quantities.",
        "- Model selection: ETS (smooth demand) or Croston-SBA / TSB (intermittent demand) replaces the baseline only "
        "when a rolling-origin backtest on the training history shows a > 5% lower WMAPE (D-45).",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="28-day replay: forecast WMAPE and reorder-decision accuracy"
    )
    parser.add_argument("--profile", default="full", choices=["full", "small", "tiny"])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    with tempfile.TemporaryDirectory() as tmp:
        generate(GeneratorConfig(profile=args.profile, seed=args.seed), Path(tmp))
        ds = load_dataset(Path(tmp))
    ev = evaluate(ds, args.profile, args.seed)
    args.out.write_text(render(ev), encoding="utf-8")
    for v in VARIANTS:
        m = metrics(ev.rows[ev.rows["variant"] == v])
        print(
            f"{v:16} WMAPE {_pct(m['wmape']):>7}  bias {_pct(m['bias']):>7}  need accuracy {_pct(m['accuracy'])}"
        )
    print(f"Report written to {args.out}")


if __name__ == "__main__":
    main()
